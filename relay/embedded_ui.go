package main

import (
	"embed"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

// The app parses the pack the relay pushes from <cwd>/.pig/android-ui and
// requires manifest.json before anything else. A fresh install has only the
// empty directories install-termux.sh creates, so every push used to answer
// "UI pack 未应用: manifest.json 缺失" and the app stayed on its bundled theme —
// the provider window and live nav entries never showed up.
//
// The relay therefore carries a default pack (examples/ui-pack-ember) and fills
// only the files that are missing. It is deliberately a different design from
// the pack the APK bundles (examples/ui-pack-compact), so the manager's two
// first rows are two distinct looks. See scripts/sync-embedded-extensions.sh.
//
//go:embed embedded/ui
var embeddedUI embed.FS

const embeddedUIDir = "embedded/ui"

// seedEmbeddedUI writes the default pack files uiDir does not have yet.
// Existing files are never touched: those directories belong to the user (a
// hand-edited theme, a pack checked out from a repository), and this only fills
// the holes that make the pack unparseable.
func (s *session) seedEmbeddedUI() {
	if s.uiDir == "" {
		return
	}
	written := 0
	err := fs.WalkDir(embeddedUI, embeddedUIDir, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil || entry.IsDir() {
			return walkErr
		}
		rel, err := filepath.Rel(embeddedUIDir, path)
		if err != nil {
			return err
		}
		rel = filepath.FromSlash(rel)
		// windows/ is generated by the extension that owns each window (for
		// example provider-ui); a shipped copy would only be stale.
		if strings.HasPrefix(filepath.ToSlash(rel), "windows/") {
			return nil
		}
		target := filepath.Join(s.uiDir, rel)
		if _, err := os.Stat(target); err == nil {
			return nil
		}
		data, err := embeddedUI.ReadFile(path)
		if err != nil {
			return err
		}
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(target, data, 0o644); err != nil {
			return err
		}
		written++
		return nil
	})
	if err != nil {
		logf("embedded ui pack: %v", err)
		return
	}
	if written > 0 {
		logf("embedded ui pack: wrote %d missing file(s) to %s", written, s.uiDir)
	}
}
